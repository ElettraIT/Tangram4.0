#==========================================*
# Moduli Perl utilizzati                   *
#------------------------------------------*
use CGI                                   ;
use PDF::Reuse                            ;
use PDF::Reuse::Barcode                   ;
use strict                                ;

#==========================================*
# Variabili lette in input                 *
#------------------------------------------*
my $cgi = new CGI;
my $num_prt = $cgi->param("prt_ods")      ;
my $rag_cli = $cgi->param("rag_cli")      ;

#==========================================*
# Eventuali normalizzazioni                *
#------------------------------------------*
if (!$num_prt || $num_prt == ''){$num_prt = "09999"};
if (!$rag_cli || $rag_cli eq ''){$rag_cli = "TEST LABEL"};

#==========================================*
# Percorsi file                            *
#------------------------------------------*
my $pth_tmp = "/abd/spl/"                 ;
my $log_az1 = "/abd/asc/mod/elettra.pdf"  ;
my $log_az2 = "/abd/asc/mod/aeg.pdf"      ;
my $out_pdf = $pth_tmp . $num_prt . ".pdf";

#==========================================*
# Stampante                                *
#------------------------------------------*
my $cod_stp = "zebra_1"                   ;

#==========================================*
# Generazione etichetta                    *
#------------------------------------------*
#------------------------------------------*
# Assegnazione nome file                   *
#------------------------------------------*
$out_pdf = $pth_tmp 
         . $num_prt
         . ".pdf"                         ;
#------------------------------------------*
# Inizializzazione file PDF                *
#------------------------------------------*
prFile($out_pdf)                          ;
#------------------------------------------*
# Impostazione pagina                      *
#------------------------------------------*
prMbox(0, 0, 285, 425)                    ;
#------------------------------------------*
# Font                                     *
#------------------------------------------*
prFont('Helvetica-Bold')                  ;
#------------------------------------------*
# Box pagina                               *
#------------------------------------------*
prAdd("q 1 1 1 rg 10 10 270 400 re b Q")  ;
#------------------------------------------*
# Fincatura superiore                      *
#------------------------------------------*
prAdd("q 50 10 m 50 410 l S Q")           ;
#------------------------------------------*
# Fincatura centrale                       *
#------------------------------------------*
prAdd("q 190 10 m 190 410 l S Q")         ; 
#------------------------------------------*
# Fincatura verticale                      *
#------------------------------------------*
#prAdd("q 190 140 m 240 140 l S Q")        ; 
#------------------------------------------*
# Fincatura inferiore                      *
#------------------------------------------*
prAdd("q 240 10 m 240 410 l S Q")         ; 
#------------------------------------------*
# Font per numero documento                *
#------------------------------------------*
prFontSize(24)                            ;       
#------------------------------------------*
# Numero documento                         *
#------------------------------------------*
my $num_ext = substr($num_prt,5,6)        ;
   $num_ext =~ s/^0+(?=[0-9])//           ;

my $str  = "ODS nr. "  
         . $num_ext                       ;
prText(40, 150, $str,'','q3')             ;
#------------------------------------------*
# Font per Ragione sociale                 *
#------------------------------------------*
prFontSize(28)                            ;       
#------------------------------------------*
# Ragione sociale                          *
#------------------------------------------*
&stp_str (90, 20, 'q3', $rag_cli)         ;
#------------------------------------------*
# Font per dicitura fissa                  *
#------------------------------------------*
prFontSize(28)                            ;       
#------------------------------------------*
# Dicitura fissa                           *
#------------------------------------------*
$str  = "CARPENTERIA PRONTA"              ;  
prText(150, 20, $str,'','q3')             ;
#------------------------------------------*
# Logo Elettra                             *
#------------------------------------------*
prImage(  { file    => $log_az1,
            page    => 1,
            imageNo => 1,
            x       => 20,
            y       => 20,
            rotate  => 'q3',
            size    => 0.2 }  )           ;
#------------------------------------------*
# Logo AEG                                 *
#------------------------------------------*
prImage(  { file    => $log_az2,
            page    => 1,
            imageNo => 1,
            x       => 20,
            y       => 340,
            rotate  => 'q3',
            size    => 0.5 }  )           ;
#------------------------------------------*
# Barcode per Numero documento             *
#------------------------------------------*
PDF::Reuse::Barcode::Code128(x      => 235,
                             y      => 30,
                             value  => $num_ext,
                             rotate => 90);
#------------------------------------------*
# Chiusura PDF                             *
#------------------------------------------*
prEnd()                                   ;
#------------------------------------------*
# Chiusura modulo                          *
#                                          *
# (???)                                    *
#------------------------------------------*
print "Content-type: text/html\n\n"       ;
#------------------------------------------*
# Stampa file PDF                          *
#------------------------------------------*
system("cat $out_pdf | lpr -P$cod_stp")   ;

#==========================================*
# Stampa stringa con eventuale ritaratura  *
# del font size                            *
#------------------------------------------*
sub stp_str
{
    #======================================*
    # Variabili in input                   *
    #--------------------------------------*
    my $xxx = shift                       ;
    my $yyy = shift                       ;
    my $rot = shift                       ;
    my $str = shift                       ;
    #--------------------------------------*
    # Pulizia spazi vuoti a fine stringa   *
    #--------------------------------------*
    $str =~ s/\s+$//                      ;
    #--------------------------------------*
    # Determinazione lunghezza stringa     *
    #--------------------------------------*
    my $lun = length($str)                ;
    #--------------------------------------*
    # Eventuale ritaratura FontSize        *
    #--------------------------------------*
    if ($lun >= 10)
    {
        prFontSize(20)                    ;       
    }
     else
    {
        prFontSize(30)                    ;       
    }
    #--------------------------------------*
    # Emissione stringa                    *
    #--------------------------------------*
    prText($xxx, $yyy, $str, '', $rot)    ;
}

