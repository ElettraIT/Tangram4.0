$(document).ready(function()
{
    /*------------------------------------*/
    /* Focus                              */
    /*------------------------------------*/
    $('#pro').focus()                     ;
    /*------------------------------------*/
    /* Codice per box info da hidden      */
    /*------------------------------------*/
    var cod = $("#sel").val()             ;
    /*------------------------------------*/
    /* Definizione box di dialogo         */
    /*------------------------------------*/
    $("#dialog").dialog({
        autoOpen: false,
        modal: true,
        title: cod,
        width: 800,
        height: 400,
    });

    /*------------------------------------*/
    /* Bottone 'info'                     */
    /*------------------------------------*/
    $("#inf").click(function ()
    {
        /*--------------------------------*/
        /* Riempimento box                */
        /*--------------------------------*/
        $.ajax({
            type: "POST",
            url: "./eletest1",
            contentType: "application/x-www-form-urlencoded",
            data: "alf_pro=" + cod,
            success: function (data)
            {
                $("#dialog").html(data);
                $("#dialog").dialog("open");
            }
        });
    });

/*----------------------------------------*/
/* Fine controllo dei dati                */
/*========================================*/
});

