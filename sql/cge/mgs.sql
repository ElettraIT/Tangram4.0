  PRIMARY KEY                                          (ann_ese,
                                                        tip_rec,
                                                        cod_con,
                                                        inx_mes),
/*       *=======================================================*/
/*       * Anno di esercizio                                     */
/*       *-------------------------------------------------------*/
  ann_ese                   integer (04)                not null,
/*       *-------------------------------------------------------*/
/*       * Tipo record                                           */
/*       *                                                       */
/*       *  - 'G' = generale                                     */
/*       *  - 'C' = clienti                                      */
/*       *  - 'F' = fornitori                                    */
/*       *-------------------------------------------------------*/
  tip_rec                   varchar (01)                not null,
/*       *-------------------------------------------------------*/
/*       * Codice conto                                          */
/*       *-------------------------------------------------------*/
  cod_con                   integer (07)                not null,
/*       *-------------------------------------------------------*/
/*       * Data ultima chiusura                                  */
/*       *                                                       */
/*       * N.B. : solo scaglione a zero                          */
/*       *-------------------------------------------------------*/
  dat_chi                   date                            null,
/*       *-------------------------------------------------------*/
/*       * Indice mensile                                        */
/*       *                                                       */
/*       * N.B. : mese zero per inizio esercizio                 */
/*       *        - Saldo iniziale                               */
/*       *        - Progr. dare  mov. di bilancio                */
/*       *        - Progr. avere mov. di bilancio                */
/*       *-------------------------------------------------------*/
  inx_mes                   tinyint (02)                not null,
/*       *-------------------------------------------------------*/
/*       * Progressivi dare mensile                              */
/*       *                                                       */
/*       * N.B. : mese zero  = Progr. di bilancio                */
/*       *-------------------------------------------------------*/
  dar_mes                   bigint (13)                 not null,
/*       *-------------------------------------------------------*/
/*       * Progressivi avere mensile                             */
/*       *                                                       */
/*       * N.B. : mese zero  = Progr. di bilancio                */
/*       *-------------------------------------------------------*/
  ave_mes                   bigint (13)                 not null,
/*       *-------------------------------------------------------*/
/*       * Flag D o A importo rettifica per mese                 */
/*       *-------------------------------------------------------*/
  dav_ret                   varchar (01)                not null,
/*       *-------------------------------------------------------*/
/*       * Importo rettifica per mese                            */
/*       *                                                       */
/*       * N.B. : mese zero  = Saldo iniziale                    */
/*       *-------------------------------------------------------*/
  imp_ret                   bigint (13)                 not null
