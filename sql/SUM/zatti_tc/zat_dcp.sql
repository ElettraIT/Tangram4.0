/*       *                                                       */
/*       *  - 01 : Normale                                       */
/*       *  - 11 : Ad esaurimento                                */
/*       *  - 21 : Sostituito da ns. nuovo prodotto              */
/*       *  - 51 : Cessata commercializzazione                   */
/*       *  - 52 : Cessata commercializzazione, ma sostituito da */
/*       *         ns. nuovo prodotto                            */
/*       *  - 71 : Obsoleto                                      */
/*       *  - 72 : Obsoleto, ma sostituito da ns. nuovo prodotto */
