/*       *-------------------------------------------------------*/
  lot_ven                   decimal (10,03)             not null,
/*       *-------------------------------------------------------*/
/*       * Dimensioni del prodotto                               */
/*       *                                                       */
/*       * - Larghezza                                           */
/*       * - Altezza                                             */
/*       * - Profondita'                                         */
/*       *-------------------------------------------------------*/
  dim_lar                   decimal (10,03)             not null,
  dim_alt                   decimal (10,03)             not null,
  dim_prf                   decimal (10,03)             not null,
