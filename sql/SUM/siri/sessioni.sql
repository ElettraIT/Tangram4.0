CREATE TABLE sessioni (
   PRIMARY KEY (idx_sss),
/*       *=======================================================*/
/*       * Id sessione MD5 random a 32 byte                      */
/*       *-------------------------------------------------------*/
  idx_sss                   varchar  (32)               not null,
/*       *-------------------------------------------------------*/
/*       * Livello operativo                                     */
/*       *-------------------------------------------------------*/
  liv_sss                   tinyint  (01)               not null,
/*       *-------------------------------------------------------*/
/*       * Codice utente                                         */
/*       *-------------------------------------------------------*/
  cod_ute                   varchar  (20)               not null,
/*       *-------------------------------------------------------*/
/*       * IP client utente                                      */
/*       *-------------------------------------------------------*/
  ipc_ute                   varchar  (20)               not null,
/*       *-------------------------------------------------------*/
/*       * Data inizio sessione                                  */
/*       *-------------------------------------------------------*/
  din_sss                   date                        not null,
/*       *-------------------------------------------------------*/
/*       * Ora inizio sessione                                   */
/*       *-------------------------------------------------------*/
  oin_sss                   time                        not null,
/*       *-------------------------------------------------------*/
/*       * Data fine sessione                                    */
/*       *-------------------------------------------------------*/
  dfi_sss                   date                        not null,
/*       *-------------------------------------------------------*/
/*       * Ora fine sessione                                     */
/*       *-------------------------------------------------------*/
  ofi_sss                   time                        not null
);

