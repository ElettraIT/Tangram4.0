CREATE TABLE utenti (
   PRIMARY KEY (utente),
/*       *-------------------------------------------------------*/
/*       * Codice utente                                         */
/*       *-------------------------------------------------------*/
   utente                   varchar  (08)               not null,
/*       *-------------------------------------------------------*/
/*       * Descrizione utente                                    */
/*       *-------------------------------------------------------*/
   descri                   varchar  (40)               not null,
/*       *-------------------------------------------------------*/
/*       * Password utente (MD5)                                 */
/*       *-------------------------------------------------------*/
   passwd                   varchar  (32)               not null,
/*       *-------------------------------------------------------*/
/*       * Ultima sessione, inizio                               */
/*       *                                                       */
/*       * ___ DA IMPLEMENTARE ___                               */
/*       *-------------------------------------------------------*/
/* sssini                   datetime                    not null,*/
/*       *-------------------------------------------------------*/
/*       * Ultima sessione, fine                                 */
/*       *                                                       */
/*       * ___ DA IMPLEMENTARE ___                               */
/*       *-------------------------------------------------------*/
/* sssend                   datetime                    not null,*/
/*       *-------------------------------------------------------*/
/*       * Tipo utente                                           */
/*       *                                                       */
/*       * - 00 : Normale                                        */
/*       * - 01 : Privilegiato                                   */
/*       * - 02 : Supervisore                                    */
/*       * - 99 : Ospite                                         */
/*       *-------------------------------------------------------*/
  tipute                    tinyint  (02)               not null
);
