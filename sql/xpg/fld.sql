/*       *=======================================================*/
/*       * Definizione delle chiavi                              */
/*       *-------------------------------------------------------*/
  PRIMARY KEY                                          (cod_tbl,
                                                        cod_fld),

/*       *=======================================================*/
/*       * Codice tabella                                        */
/*       *-------------------------------------------------------*/
  cod_tbl                   varchar  (10)               not null default '',

/*       *-------------------------------------------------------*/
/*       * Codice campo                                          */
/*       *-------------------------------------------------------*/
  cod_fld                   varchar  (30)               not null default '',

/*       *-------------------------------------------------------*/
/*       * Descrizione campo                                     */
/*       *-------------------------------------------------------*/
  des_fld                   varchar  (80)               not null default '',

/*       *-------------------------------------------------------*/
/*       * Ruolo strutturale                                     */
/*       *                                                       */
/*       * - K : Campo chiave                                    */
/*       * - T : Campo di testata                                */
/*       * - R : Campo di riga                                   */
/*       * - P : Campo di piede                                  */
/*       *-------------------------------------------------------*/
  rls_fld                   char     (01)               not null default 'T',

/*       *-------------------------------------------------------*/
/*       * Tipo campo                                            */
/*       *                                                       */
/*       * - T : Testo                                           */
/*       * - N : Numero                                          */
/*       * - D : Data                                            */
/*       * - B : Booleano                                        */
/*       * - E : Enumerativo                                     */
/*       *-------------------------------------------------------*/
  tip_fld                   char     (01)               not null default 'T',

/*       *-------------------------------------------------------*/
/*       * Lunghezza campo                                       */
/*       *-------------------------------------------------------*/
  lun_fld                   integer                     not null default 0,

/*       *-------------------------------------------------------*/
/*       * Decimali campo                                        */
/*       *-------------------------------------------------------*/
  dec_fld                   integer                     not null default 0,

/*       *-------------------------------------------------------*/
/*       * Si/no lookup                                          */
/*       *                                                       */
/*       * - 0 : No                                              */
/*       * - 1 : Si                                              */
/*       *-------------------------------------------------------*/
  snx_lkp                   tinyint  (01)               not null default 0,

/*       *-------------------------------------------------------*/
/*       * Tabella lookup                                        */
/*       *-------------------------------------------------------*/
  tab_lkp                   varchar  (10)               not null default '',

/*       *-------------------------------------------------------*/
/*       * Chiave tabella lookup                                 */
/*       *-------------------------------------------------------*/
  key_lkp                   varchar  (30)               not null default '',

/*       *-------------------------------------------------------*/
/*       * Descrizione tabella lookup                            */
/*       *-------------------------------------------------------*/
  des_lkp                   varchar  (30)               not null default '',

/*       *-------------------------------------------------------*/
/*       * Parametro tabella lookup                              */
/*       *                                                       */
/*       * Utilizzabile per discriminare casi particolari        */
/*       * della stessa tabella lookup                           */
/*       *                                                       */
/*       * Esempio: zst                                           */
/*       * - 01 : Zone                                           */
/*       * - 02 : Categorie                                      */
/*       * - 03 : Codici statistici                              */
/*       *-------------------------------------------------------*/
  par_lkp                   varchar  (20)               not null default '',

/*       *-------------------------------------------------------*/
/*       * Help note                                             */
/*       *-------------------------------------------------------*/
  hlp_fld                   varchar  (255)              not null default ''