  PRIMARY KEY                                          (cod_stp),
/*       *=======================================================*/
/*       * Codice stampante                                      */
/*       *-------------------------------------------------------*/
  cod_stp                   varchar  (08)               not null,
/*       *-------------------------------------------------------*/
/*       * Descrizione stampante                                 */
/*       *-------------------------------------------------------*/
  des_stp                   varchar  (80)               not null,
/*       *-------------------------------------------------------*/
/*       * Tipo stampante                                        */
/*       *-------------------------------------------------------*/
  tip_stp                   varchar  (10)               not null,
/*       *-------------------------------------------------------*/
/*       * Canale di uscita                                      */
/*       *-------------------------------------------------------*/
  can_stp                   varchar  (80)               not null,
/*       *-------------------------------------------------------*/
/*       * Password per la stampante                             */
/*       *-------------------------------------------------------*/
  pwd_stp                   varchar  (08)               not null,   
/*       *-------------------------------------------------------*/
/*       * Password per documento generato dalla stampante       */
/*       *-------------------------------------------------------*/
  pwd_pdg                   varchar  (08)               not null,   
/*       *-------------------------------------------------------*/
/*       * Flag di inibizione del form feed finale in caso       */
/*       * di stampa in spool                                    */
/*       *                                                       */
/*       * - N : Non inibito, valore di default                  */
/*       * - S : Inibito                                         */
/*       *-------------------------------------------------------*/
  flg_spl                   varchar  (01)               not null,
/*       *-------------------------------------------------------*/
/*       * Ubicazione abituale stampante                         */
/*       *-------------------------------------------------------*/
  des_ubi                   varchar  (80)               not null,
/*       *-------------------------------------------------------*/
/*       * Status stampante                                      */
/*       *                                                       */
/*       * - ' ' o 'A' : Attiva                                  */
/*       * - 'N'       : Stampante obsoleta                      */
/*       *                                                       */
/*       * N.B.: attualmente non gestito                         */
/*       *-------------------------------------------------------*/
  sts_stp                   varchar  (01)               not null,
/*       *-------------------------------------------------------*/
/*       * Percorso immagine                                     */
/*       *-------------------------------------------------------*/
  pth_img                   varchar  (80)               not null
