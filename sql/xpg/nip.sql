/*    *==========================================================*/
/*    * Tabella [nip] Nodi IP impianto                     {xpg} */
/*    *                                                          */
/*    * Aggiornamento 14.04.2009                                 */
/*    *----------------------------------------------------------*/
/*       *=======================================================*/
/*       * Definizione delle chiavi                              */
/*       *-------------------------------------------------------*/
  PRIMARY KEY                                          (cod_nip),
/*       *=======================================================*/
/*       * Codice nodo IP                                        */
/*       *-------------------------------------------------------*/
  cod_nip                   varchar  (08)               not null,
/*       *-------------------------------------------------------*/
/*       * Descrizione nodo IP                                   */
/*       *-------------------------------------------------------*/
  des_nip                   varchar  (80)               not null,
/*       *-------------------------------------------------------*/
/*       * Tipo nodo IP                                          */
/*       *                                                       */
/*       * - 01 : Server                                         */
/*       * - 02 : Computer client di rete                        */
/*       * - 03 : Stampante di rete                              */
/*       * - 04 : Print-server                                   */
/*       * - 05 : Router o gateway                               */
/*       * - 06 : Access Point Wireless                          */
/*       * - 07 : Device Point Wireless                          */
/*       * - 08 : Network Camera                                 */
/*       *-------------------------------------------------------*/
  tip_nip                   tinyint  (02)               not null,
/*       *-------------------------------------------------------*/
/*       * Codice utente                                         */
/*       *-------------------------------------------------------*/
  ute_nip                   varchar  (08)               not null,
/*       *-------------------------------------------------------*/
/*       * Versione rete IP                                      */
/*       *                                                       */
/*       * - 01 : ip4 000.000.000.000                            */
/*       * - 02 : ip6 000.000.000.000.000.000                    */
/*       *                                                       */
/*       * N.B. : campo attualmente non gestito                  */
/*       *-------------------------------------------------------*/
  ver_nip                   tinyint  (02)               not null,
/*       *-------------------------------------------------------*/
/*       * Indirizzo IP di rete                                  */
/*       *-------------------------------------------------------*/
  iip_nip                   varchar  (40)               not null,
/*       *-------------------------------------------------------*/
/*       * Eventuale nome di rete                                */
/*       *-------------------------------------------------------*/
  nom_nip                   varchar  (80)               not null,
/*       *-------------------------------------------------------*/
/*       * Numero identificatore interno                         */
/*       *-------------------------------------------------------*/
  num_nip                   varchar  (20)               not null,
/*       *-------------------------------------------------------*/
/*       * Ubicazione nodo                                       */
/*       *-------------------------------------------------------*/
  ubi_nip                   varchar  (80)               not null,
/*       *-------------------------------------------------------*/
/*       * Sistema operativo                                     */
/*       *-------------------------------------------------------*/
  oss_nip                   varchar  (80)               not null,
/*       *-------------------------------------------------------*/
/*       * Aggiornamento nodo                                    */
/*       *-------------------------------------------------------*/
  agg_nip                   date                        not null,
/*       *-------------------------------------------------------*/
/*       * Matricola                                             */
/*       *-------------------------------------------------------*/
  mtr_nip                   varchar  (80)               not null,
/*       *-------------------------------------------------------*/
/*       * Capacita' dispositivo                                 */
/*       *-------------------------------------------------------*/
  cpd_nip                   varchar  (80)               not null,
/*       *-------------------------------------------------------*/
/*       * Username dispositivo                                  */
/*       *-------------------------------------------------------*/
  usr_nip                   varchar  (20)               not null,
/*       *-------------------------------------------------------*/
/*       * Password dispositivo                                  */
/*       *-------------------------------------------------------*/
  pwd_nip                   varchar  (20)               not null,
/*       *-------------------------------------------------------*/
/*       * Caratteristiche descrittive nodo                      */
/*       *-------------------------------------------------------*/
  not_nip                   varchar  (120)              not null,
/*       *-------------------------------------------------------*/
/*       * Status nodo IP                                        */
/*       *                                                       */
/*       * - 01 : Attivo                                         */
/*       * - 02 : Obsoleto                                       */
/*       *-------------------------------------------------------*/
  sts_nip                   tinyint  (02)               not null
