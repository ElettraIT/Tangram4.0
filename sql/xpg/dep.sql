/*    *==========================================================*/
/*    * Tabella [dep] Definizione delle personalizzazioni  {xpg} */
/*    *                                                          */
/*    * Aggiornamento 20.01.2005                                 */
/*    *----------------------------------------------------------*/
/*       *=======================================================*/
/*       * Definizione delle chiavi                              */
/*       *-------------------------------------------------------*/
  PRIMARY KEY                                          (cod_dep),
/*       *=======================================================*/
/*       * Codice definizione personalizzazione                  */
/*       *-------------------------------------------------------*/
  cod_dep                   varchar  (40)               not null,
/*       *-------------------------------------------------------*/
/*       * Descrizione definizione personalizzazione             */
/*       *-------------------------------------------------------*/
  des_dep                   varchar  (80)               not null,
/*       *-------------------------------------------------------*/
/*       * Tipo personalizzazione                                */
/*       *                                                       */
/*       *  - A : Alfanumerica                                   */
/*       *  - N : Numerica                                       */
/*       *  - D : Data                                           */
/*       *  - T : Text                                           */
/*       *-------------------------------------------------------*/
  tip_dep                   varchar  (01)               not null,
/*       *-------------------------------------------------------*/
/*       * Numero caratteri, se alfanumerica o numerica          */
/*       *-------------------------------------------------------*/
  car_dep                   integer  (03)               not null,
/*       *-------------------------------------------------------*/
/*       * Numero decimali, se numerica                          */
/*       *-------------------------------------------------------*/
  dec_dep                   tinyint  (01)               not null,
/*       *-------------------------------------------------------*/
/*       * Segno algebrico, se numerica                          */
/*       *                                                       */
/*       *  - Spaces : No                                        */
/*       *  - S      : Si'                                       */
/*       *-------------------------------------------------------*/
  sgn_dep                   varchar  (01)               not null,
/*       *-------------------------------------------------------*/
/*       * Personalizzazione singola o multipla                  */
/*       *                                                       */
/*       *  - S : Singola                                        */
/*       *  - M : Multipla                                       */
/*       *                                                       */
/*       * Campo attualmente forzato a 'S'                       */
/*       *-------------------------------------------------------*/
  som_dep                   varchar  (01)               not null,
/*       *-------------------------------------------------------*/
/*       * Commento per la personalizzazione                     */
/*       *-------------------------------------------------------*/
  not_dep                   varchar  (240)              not null