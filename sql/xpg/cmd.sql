/*    *----------------------------------------------------------*/
/*       *=======================================================*/
/*       * Definizione delle chiavi                              */
/*       *-------------------------------------------------------*/
  PRIMARY KEY                                          (cod_cmd),
/*       *=======================================================*/
/*       * Codice comando                                        */
/*       *-------------------------------------------------------*/
  cod_cmd                   varchar  (06)               not null,
/*       *-------------------------------------------------------*/
/*       * Descrizione comando                                   */
/*       *-------------------------------------------------------*/
  des_cmd                   varchar  (40)               not null,
/*       *-------------------------------------------------------*/
/*       * Tipo comando                                          */
/*       *                                                       */
/*       * - 00 : Task                                           */
/*       * - 01 : Menu                                           */
/*       * - 99 : Alias per un altro comando                     */
/*       *-------------------------------------------------------*/
  tip_cmd                   tinyint  (02)               not null,
/*       *-------------------------------------------------------*/
/*       * Percorso comando                                      */
/*       *-------------------------------------------------------*/
  pth_cmd                   varchar  (40)               not null,
/*       *-------------------------------------------------------*/
/*       * Gerarchia comando                                     */
/*       *                                                  liv  */
/*       * - Sistema   applicativo       (X) (sys,std,SUM)   0   */
/*       * - Menu      gestionale        (M) (am,ge,ve)      1   */
/*       * - Area      gestionale        (A) (cge,fat)       2   */
/*       * - Settore   gestionale        (S) (cgemov)        3   */
/*       * - Fase      gestionale        (F) (cge300)        4   */
/*       *-------------------------------------------------------*/
  l00_cmd                   varchar  (03)               not null,
  l01_cmd                   varchar  (03)               not null,
  l02_cmd                   varchar  (03)               not null,
  l03_cmd                   varchar  (06)               not null,
  l04_cmd                   varchar  (06)               not null,
/*       *-------------------------------------------------------*/
/*       * Nome programma                                        */
/*       *-------------------------------------------------------*/
  prg_cmd                   varchar  (08)               not null,
/*       *-------------------------------------------------------*/
/*       * Menu' di rientro                                      */
/*       *-------------------------------------------------------*/
  mnu_rie                   varchar  (06)               not null,
/*       *-------------------------------------------------------*/
/*       * Password comando                                      */
/*       *-------------------------------------------------------*/
  pwd_cmd                   varchar  (08)               not null,   
/*       *-------------------------------------------------------*/
/*       * Tipo di utente che puo' operare                       */
/*       *                                                       */
/*       * - 00 : Normale - Privilegiato - Supervisore           */
/*       * - 01 : Privilegiato - Supervisore                     */
/*       * - 02 : Supervisore                                    */
/*       *-------------------------------------------------------*/
  tip_ute                   tinyint  (02)               not null,
/*       *-------------------------------------------------------*/
/*       * Livello di protezione                                 */
/*       *                                                       */
/*       * N.B.: Non gestito                                     */
/*       *-------------------------------------------------------*/
  liv_pro                   integer  (06)               not null,
/*       *-------------------------------------------------------*/
/*       * Status comando                                        */
/*       *                                                       */
/*       * - 00 : Puo' operare                                   */
/*       * - 01 : Bloccato                                       */
/*       *-------------------------------------------------------*/
  sts_cmd                   tinyint  (02)               not null,
/*       *-------------------------------------------------------*/
/*       * Tipo Task                                             */
/*       *                                                       */
/*       * - 00 : (non significativo)                            */
/*       * - 01 : Gestione o manutenzione o batch                */
/*       * - 02 : Interrogazione                                 */
/*       * - 03 : Stampa                                         */
/*       *                                                       */
/*       * N.B. : solo se comando di tipo 'task'                 */
/*       *-------------------------------------------------------*/
  tip_tsk                   tinyint  (02)               not null,
/*       *-------------------------------------------------------*/
/*       * Ordinatore di posizione comando                       */
/*       *-------------------------------------------------------*/
  ord_cmd                   tinyint  (02)               not null