/*    *----------------------------------------------------------*/
/*       *=======================================================*/
/*       * Definizione delle chiavi                              */
/*       *-------------------------------------------------------*/
  PRIMARY KEY                                          (cod_der),
/*       *=======================================================*/
/*       * Codice definizione referenza                          */
/*       *-------------------------------------------------------*/
  cod_der                   varchar  (40)               not null,
/*       *-------------------------------------------------------*/
/*       * Descrizione definizione referenza                     */
/*       *-------------------------------------------------------*/
  des_der                   varchar  (80)               not null,
/*       *-------------------------------------------------------*/
/*       * Tipo referenza                                        */
/*       *                                                       */
/*       *  - A : Alfanumerica                                   */
/*       *  - N : Numerica                                       */
/*       *  - D : Data                                           */
/*       *  - T : Text                                           */
/*       *-------------------------------------------------------*/
  tip_der                   varchar  (01)               not null,
/*       *-------------------------------------------------------*/
/*       * Numero caratteri, se alfanumerica o numerica          */
/*       *-------------------------------------------------------*/
  car_der                   integer  (03)               not null,
/*       *-------------------------------------------------------*/
/*       * Numero decimali, se numerica                          */
/*       *-------------------------------------------------------*/
  dec_der                   tinyint  (01)               not null,
/*       *-------------------------------------------------------*/
/*       * Segno algebrico, se numerica                          */
/*       *                                                       */
/*       *  - Spaces : No                                        */
/*       *  - S      : Si'                                       */
/*       *-------------------------------------------------------*/
  sgn_der                   varchar  (01)               not null,
/*       *-------------------------------------------------------*/
/*       * Personalizzazione singola o multipla                  */
/*       *                                                       */
/*       *  - S : Singola                                        */
/*       *  - M : Multipla                                       */
/*       *                                                       */
/*       * Campo attualmente forzato a 'S'                       */
/*       *-------------------------------------------------------*/
  som_der                   varchar  (01)               not null,
/*       *-------------------------------------------------------*/
/*       * Commento per la personalizzazione                     */
/*       *-------------------------------------------------------*/
  not_der                   varchar  (240)              not null
