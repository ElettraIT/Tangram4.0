/*       * Definizione delle chiavi                              */
/*       *-------------------------------------------------------*/
  PRIMARY KEY                                          (cod_fas,
                                                        pag_fld,
                                                        tix_fld),
/*       *=======================================================*/
/*       * Codice fase                                           */
/*       *-------------------------------------------------------*/
  cod_fas                   varchar  (08)               not null,
/*       *-------------------------------------------------------*/
/*       * Pagina di visualizzazione                             */
/*       *-------------------------------------------------------*/
  pag_fld                   tinyint  (02)               not null,
/*       *-------------------------------------------------------*/
/*       * Ordine di accettazione                                */
/*       *-------------------------------------------------------*/
  tix_fld                   tinyint  (03)               not null,
/*       *-------------------------------------------------------*/
/*       * Codice campo                                          */
/*       *-------------------------------------------------------*/
  cod_fld                   varchar  (08)               not null,
/*       *-------------------------------------------------------*/
/*       * Codice campo alternativo                              */
/*       *-------------------------------------------------------*/
  alt_fld                   varchar  (08)               not null,
/*       *-------------------------------------------------------*/
/*       * Prompt campo                                          */
/*       *-------------------------------------------------------*/
  pmt_fld                   varchar  (80)               not null,
/*       *-------------------------------------------------------*/
/*       * Tipo campo                                            */
/*       *-------------------------------------------------------*/
  tip_fld                   varchar  (02)               not null,
/*       *-------------------------------------------------------*/
/*       * Tipo impiego                                          */
/*       *                                                       */
/*       * - K : Campo chiave                                    */
/*       * - T : Campo di testata                                */
/*       * - R : Campo di riga                                   */
/*       * - P : Campo di piede                                  */
/*       *-------------------------------------------------------*/
  tip_imp                   varchar  (02)               not null,
/*       *-------------------------------------------------------*/
/*       * Tipo di riga in tabella                               */
/*       *                                                       */
/*       * - A : Campo senza descrittivo                         */
/*       * - B : Campo con descrittivo                           */
/*       * - C : Campo senza descrittivo, con messagio           */
/*       * - S : Separatore vuoto                                */
/*       *-------------------------------------------------------*/
  tip_rig                   varchar  (02)               not null,
/*       *-------------------------------------------------------*/
/*       * Nome campo di lettura                                 */
/*       *-------------------------------------------------------*/
  let_fld                   varchar  (08)               not null,
/*       *-------------------------------------------------------*/
/*       * Nome modulo di inserimento                            */
/*       *-------------------------------------------------------*/
  ins_mod                   varchar  (08)               not null,
/*       *-------------------------------------------------------*/
/*       * Nome modulo di ricerca                                */
/*       *-------------------------------------------------------*/
  fnd_mod                   varchar  (08)               not null,
/*       *-------------------------------------------------------*/
/*       * Presenza riga descrittiva                             */
/*       *-------------------------------------------------------*/
  rig_acc                   tinyint  (03)               not null,
/*       *-------------------------------------------------------*/
/*       * Massimo caratteri accettabili                         */
/*       *-------------------------------------------------------*/
  lun_fld                   tinyint  (03)               not null,
/*       *-------------------------------------------------------*/
/*       * Lunghezza box di accettazione                         */
/*       *-------------------------------------------------------*/
  box_fld                   tinyint  (03)               not null
