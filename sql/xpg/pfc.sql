/*       *-------------------------------------------------------*/
  snx_vis                   char(01)        NOT NULL DEFAULT 'N',
/*       *-------------------------------------------------------*/
/*       * Si/no condiviso                                       */
/*       *-------------------------------------------------------*/
  snx_shd                   char(01)        NOT NULL DEFAULT 'N',
/*       *-------------------------------------------------------*/
/*       * ID job                                                */
/*       *-------------------------------------------------------*/
  job_idx                   integer        unsigned default null
