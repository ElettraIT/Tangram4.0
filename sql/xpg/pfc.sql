  fil_pth                   varchar(255)                not null,
/*       *-------------------------------------------------------*/
/*       * Codice modulo                                         */
/*       *-------------------------------------------------------*/
  cod_mod                   varchar (20)                not null,
/*       *-------------------------------------------------------*/
