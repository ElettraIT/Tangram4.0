  num_prt                   bigint  (11)                not null,

/*==============================================================*/
/* Tabella [bse] Eventi di tracking spedizioni da bolle         */
/*==============================================================*/
CREATE TABLE bse (
/*--------------------------------------------------------------*/
/* Identificativo evento                                        */
/*--------------------------------------------------------------*/
  bse_id                    bigint (11)                not null,
/*--------------------------------------------------------------*/
/* Riferimento spedizione (testata BSP)                         */
/*--------------------------------------------------------------*/
  bsp_id                    bigint (11)                not null,
/*--------------------------------------------------------------*/
/* Data/ora evento (dati del vettore)                           */
/*--------------------------------------------------------------*/
  dat_evt                   date                       not null,
  ora_evt                   integer (04)               not null,
/*--------------------------------------------------------------*/
/* Codice evento del vettore                                   */
/*--------------------------------------------------------------*/
  cod_evt_vt                varchar (20)               not null,
/*--------------------------------------------------------------*/
/* Codice evento interno normalizzato                           */
/*                                                             */
/* es. 10=Pickup, 20=Transit, 30=In consegna, 90=Consegnata...  */
/*--------------------------------------------------------------*/
  cod_evt_int               varchar (02)               not null,
/*--------------------------------------------------------------*/
/* Località / filiale                                          */
/*--------------------------------------------------------------*/
  loc_evt                   varchar (50)               not null,
/*--------------------------------------------------------------*/
/* Descrizione evento                                           */
/*--------------------------------------------------------------*/
  dsc_evt                   varchar (255)              not null,
/*--------------------------------------------------------------*/
/* Identificativi                                               */
/*--------------------------------------------------------------*/
  ide_dat                   date                       not null,
  ide_ute                   varchar (08)               not null,
  ide_fas                   varchar (06)               not null,

  PRIMARY KEY (bse_id)
);

CREATE INDEX bse_i1 ON bse (bsp_id, dat_evt, ora_evt);
