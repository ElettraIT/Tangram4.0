/*==============================================================*/
/* Tabella [bsp] Spedizioni da bolle clienti : testate          */
/*==============================================================*/
CREATE TABLE bsp (
/*--------------------------------------------------------------*/
/* Identificativo spedizione                                    */
/*--------------------------------------------------------------*/
  bsp_id                    bigint (11)                not null,
/*--------------------------------------------------------------*/
/* Bolla di riferimento                                         */
/*--------------------------------------------------------------*/
  num_prt                   bigint (11)                not null,
/*--------------------------------------------------------------*/
/* Vettore effettivo (riprende cod_vet di BIT o altro)          */
/*--------------------------------------------------------------*/
  cod_vet                   integer (07)               not null,
/*--------------------------------------------------------------*/
/* Numero tracking vettore                                      */
/*--------------------------------------------------------------*/
  trk_num                   varchar (40)               not null,
/*--------------------------------------------------------------*/
/* Stato interno spedizione (come trk_sts in BIT)               */
/*--------------------------------------------------------------*/
  trk_sts                   varchar (02)               not null,
/*--------------------------------------------------------------*/
/* Data/ora creazione spedizione                                */
/*--------------------------------------------------------------*/
  dat_cre                   date                       not null,
  ora_cre                   integer (04)               not null,
/*--------------------------------------------------------------*/
/* Data/ora chiusura (consegna o annullo)                       */
/*--------------------------------------------------------------*/
  dat_chs                   date                       not null,
  ora_chs                   integer (04)               not null,
/*--------------------------------------------------------------*/
/* Identificativi                                               */
/*--------------------------------------------------------------*/
  ide_dat                   date                       not null,
  ide_ute                   varchar (08)               not null,
  ide_fas                   varchar (06)               not null,

  PRIMARY KEY (bsp_id)
);

/* Indici utili */
CREATE INDEX bsp_i1 ON bsp (num_prt);
CREATE INDEX bsp_i2 ON bsp (trk_num);


