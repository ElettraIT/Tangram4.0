/*    * Identificativi elettronici anagrafici (SDI/EDI/Peppol)   */
/*    *                                                          */
/*    * Aggiornamento 25.04.2026                                 */
/*    *----------------------------------------------------------*/
/*       *=======================================================*/
/*       * Definizione delle chiavi                              */
/*       *-------------------------------------------------------*/
  PRIMARY KEY                                          (tip_arc,
                                                        cod_arc,
                                                        dpz_arc,
                                                        tip_key,
                                                        sch_key,
                                                        val_key),
/*       *=======================================================*/
/*       * Tipo archivio                                         */
/*       *                                                       */
/*       * - 00 : Azienda                                        */
/*       * - 01 : Cliente                                        */
/*       * - 11 : Fornitore                                      */
/*       * - 31 : Agente                                         */
/*       * - 41 : Vettore                                        */
/*       *-------------------------------------------------------*/
  tip_arc                   tinyint (02)                not null,
/*       *=======================================================*/
/*       * Codice archivio                                       */
/*       *-------------------------------------------------------*/
  cod_arc                   integer (07)                not null,
/*       *=======================================================*/
/*       * Codice dipendenza archivio                            */
/*       *-------------------------------------------------------*/
  dpz_arc                   varchar (07)                not null,
/*       *=======================================================*/
/*       * Tipo chiave                                           */
/*       *                                                       */
/*       * - 'SDI' : codice SDI                                  */
/*       * - 'MET' : codice per EDI (Metel)                      */
/*       * - 'ASS' : codice assegnato dal codice archivio        */
/*       *-------------------------------------------------------*/
  tip_key                   varchar (03)                not null,
/*       *=======================================================*/
/*       * Schema chiave                                         */
/*       *-------------------------------------------------------*/
  sch_key                   varchar (04)                not null,
/*       *=======================================================*/
/*       * Valore chiave                                         */
/*       *                                                       */
/*       * Identificativo elettronico                            */
/*       *-------------------------------------------------------*/
  val_key                   varchar (80)                not null,
/*       *-------------------------------------------------------*/
/*       * Flag chiave principale                                */
/*       *                                                       */
/*       * - 'S' : Sì                                            */
/*       * - 'N' : No                                            */
/*       *-------------------------------------------------------*/
  flg_pri                   varchar (01)                not null,
/*       *-------------------------------------------------------*/
/*       * Flag attivazione                                      */
/*       *                                                       */
/*       * - 'S' : Attiva                                        */
/*       * - 'N' : Disattiva                                     */
/*       *-------------------------------------------------------*/
  flg_att                   varchar (01)                not null,
/*       *-------------------------------------------------------*/
/*       * Data inizio validita'                                 */
/*       *-------------------------------------------------------*/
  dat_ini                   date                        not null,
/*       *-------------------------------------------------------*/
/*       * Data fine validita'                                   */
/*       *-------------------------------------------------------*/
  dat_fin                   date                        not null,
/*       *-------------------------------------------------------*/
/*       * Data aggiornamento                                    */
/*       *-------------------------------------------------------*/
  dat_agg                   date                        not null,
