/*       *-------------------------------------------------------*/
  tip_doc                   tinyint (02)                not null,
/*       *-------------------------------------------------------*/
/*       * Codice tipo movimento                                 */
/*       *-------------------------------------------------------*/
  tmo_doc                   varchar (05)                not null,
/*       *-------------------------------------------------------*/
/*       * Progressivo scaglione 1..6                            */
/*       *-------------------------------------------------------*/
  num_prg                   tinyint (02)                not null,
/*       *-------------------------------------------------------*/
/*       * Ammontare di applicazione dello sconto                */
/*       *-------------------------------------------------------*/
  sct_tot                   bigint  (13)                not null,
/*       *-------------------------------------------------------*/
/*       * Percentuale di sconto applicata                       */
/*       *-------------------------------------------------------*/
  sct_per                   decimal (05,02)             not null