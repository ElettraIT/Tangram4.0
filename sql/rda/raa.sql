  cod_fnt                   integer (07)                not null,
/*       *-------------------------------------------------------*/
/*       * Si/no persona fisica                                  */
/*       *                                                       */
/*       *  - 01 : no, non si tratta di persona fisica           */
/*       *  - 02 : si, si tratta di persona fisica               */
/*       *-------------------------------------------------------*/
  snx_prf                   tinyint (02)                not null,
/*       *-------------------------------------------------------*/
/*       * Ragione sociale fornitore (se non persona fisica)     */
/*       *-------------------------------------------------------*/
  rag_soc                   varchar (80)                not null,
/*       *-------------------------------------------------------*/
/*       * Nome                                                  */
/*       *-------------------------------------------------------*/
  nom_fnt                   varchar (80)                not null,
/*       *-------------------------------------------------------*/
/*       * Cognome                                               */
/*       *-------------------------------------------------------*/
  cgn_fnt                   varchar (80)                not null,
/*       *-------------------------------------------------------*/
/*       * Indirizzo fornitore                                   */
/*       *-------------------------------------------------------*/
  via_fnt                   varchar (80)                not null,
/*       *-------------------------------------------------------*/
/*       * C.a.p. e citta' fornitore                             */
/*       *-------------------------------------------------------*/
  loc_fnt                   varchar (80)                not null,
/*       *-------------------------------------------------------*/
/*       * Data di nascita fornitore                             */
/*       *-------------------------------------------------------*/
  dat_nsc                   date                        not null,
/*       *-------------------------------------------------------*/
/*       * Localita' di nascita fornitore                        */
/*       *-------------------------------------------------------*/
  loc_nsc                   varchar (80)                not null,
/*       *-------------------------------------------------------*/
/*       * Sesso fornitore                                       */
/*       *                                                       */
/*       *  - 01 : Maschio                                       */
/*       *  - 02 : Femmina                                       */
/*       *  - 03 : non si tratta di persona fisica               */
/*       *-------------------------------------------------------*/
  sex_fnt                   tinyint (02)                not null,
/*       *-------------------------------------------------------*/
/*       * Si/no residenza estero                                */
/*       *                                                       */
/*       *  - 01 : no, si tratta di residente in Italia          */
/*       *  - 02 : si, si tratta di residente all'estero        */
/*       *-------------------------------------------------------*/
  snx_rsi                   tinyint (02)                not null,
/*       *-------------------------------------------------------*/
/*       * Si/no trattamento provvigionale                       */
/*       *                                                       */
/*       *  - 01 : non si tratta di trattamento provvigionale    */
/*       *  - 02 : si tratta di trattamento provvigionale        */
/*       *-------------------------------------------------------*/
  snx_tpv                   tinyint (02)                not null,
/*       *-------------------------------------------------------*/
/*       * Codice causale ritenuta                               */
/*       *-------------------------------------------------------*/
  cod_cau                   integer (05)                not null,
/*       *-------------------------------------------------------*/
/*       * Codice tipo contributo                                */
/*       *-------------------------------------------------------*/
  cod_tcb                   integer (05)                not null,
/*       *-------------------------------------------------------*/
/*       * Codice tributo                                        */
/*       *-------------------------------------------------------*/
  cod_trb                   integer (05)                not null,
/*       *-------------------------------------------------------*/
/*       * Identificativi                                        */
/*       *-------------------------------------------------------*/
  ide_dat                   date                        not null,
  ide_ute                   varchar (08)                not null,
  ide_fas                   varchar (06)                not null

